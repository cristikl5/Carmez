export const findNewsBySlug = (locale: "ro" | "ru", slug?: string) => {
  if (!slug) return undefined;
  const localeNews = newsData[locale] ?? [];
  const fallbackNews =
    locale === "ro" ? (newsData.ru ?? []) : (newsData.ro ?? []);

  return (
    localeNews.find(item => item.slug === slug) ??
    fallbackNews.find(item => item.slug === slug)
  );
};

